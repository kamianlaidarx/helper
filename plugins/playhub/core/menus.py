"""47 项功能的**触发卡**：裸发关键词时回的那一张，排版全部走 `core/render.py`。

为什么要有菜单卡
----------------
小V 每个功能都自带「群内发 XX 查看」的自述卡（见 `.runtime/research/xiaov/img/`），
好处是群里新人不用记文档、也不用管理员口头教。我们原来只有一条 `帮助` 大列表，
43 个功能挤在十几行里，既没人看也说不清参数。

本模块的边界
------------
- **只放文案**：不给引擎传参、不查库、不判权限。要发什么卡由 `app.py` 决定。
- **只写能兑现的东西**：卡上出现的每个子命令、每个数值，都必须和引擎里真实的
  常量/分支对得上（如金币榜只有 `金币` 一个参数，卡上就不许写「钻石榜」）。
  功能还没实现的那 21 项只写「玩法一句话 + 参数形状」，末尾挂「还没上线」，
  绝不虚构子命令——卡面说了做不到，比没有卡更糟。
- **行数 ≤ 10**：小V 的钓鱼卡 35 行，在群里是刷屏。超过 10 行说明这个功能
  该拆子命令，而不是该发更长的卡。
"""
