def _card(action: str, icon: str, title: str, rows: tuple[str, ...], note_text: str = "", pending: bool = False) -> str:
    tail = _PENDING_TAIL if pending else ""
    return Card(icon=icon, title=title, rows=rows, note=note_text, tail=tail).render()


