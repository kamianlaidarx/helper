#: 裸发时回卡的动作集合（其余动作裸发仍是静默）
CARDED: frozenset[str] = frozenset(MENUS)


def menu_for(action: str) -> str | None:
    """取某动作的触发卡；没有卡返回 `None`（调用方据此保持静默）。"""
    return MENUS.get(action)


def is_pending(action: str) -> bool:
    """卡面是否挂「还在施工」——验收时用来核对卡面没承诺做不到的事。"""
    text = MENUS.get(action, "")
    return _PENDING_TAIL in text
